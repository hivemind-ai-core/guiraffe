#!/usr/bin/env python3
"""Showcase option-coverage audit: writes crates/showcase/COVERAGE.md.

For every type an entry `covers` (plus its `*State` entity and `*Event` enum), lists public
methods and event variants, then classifies each by how the demos use it:
  knob  - called inside a knob-driven preview fn (signature takes `&KnobValues`)
  demo  - called elsewhere in the demo module (static example / stateful demo)
  -     - missing
Name-based heuristic, good enough to spot gaps.
Run: python3 crates/showcase/tools/coverage_audit.py [--missing]
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
SC = ROOT / "crates/showcase/src/demos"
SKIP = {"new", "render", "default", "fmt", "clone", "eq", "from", "into", "id", "element_id",
        "style", "children_mut", "extend", "global", "init"}


def fns_by_type(krate):
    out = {}
    for p in (ROOT / "crates" / krate / "src").rglob("*.rs"):
        src = p.read_text()
        src = re.split(r"#\[cfg\(test\)\]\s*mod tests", src)[0]
        for m in re.finditer(r"^impl(?:<[^>{]*>)?\s+([A-Z]\w*)(?:<[^>{]*>)?\s*\{", src, re.M):
            name, start, depth, i = m.group(1), m.end(), 1, m.end()
            while depth and i < len(src):
                depth += {"{": 1, "}": -1}.get(src[i], 0)
                i += 1
            for f in re.finditer(r"^    pub (?:const )?fn (\w+)", src[start:i], re.M):
                if f.group(1) not in SKIP:
                    out.setdefault(name, []).append(f.group(1))
        for m in re.finditer(r"pub enum (\w+Event)\s*\{([^}]*)\}", src):
            vs = re.findall(r"^\s*(?:#\[[^\]]*\]\s*)*([A-Z]\w*)", m.group(2), re.M)
            out.setdefault(m.group(1), []).extend("event:" + v for v in vs)
    return out


def demo_usage(path):
    src = path.read_text()
    knob, demo = set(), set()
    for part in re.split(r"\n(?=(?:pub(?:\(crate\))? )?fn \w+)", src):
        is_knob = re.match(r"(?:pub(?:\(crate\))? )?fn \w+[^{]*KnobValues", part)
        target = knob if is_knob else demo
        target.update(re.findall(r"\.(\w+)\s*[(:<]", part))
        target.update("event:" + v for v in re.findall(r"\w+Event::(\w+)", part))
        target.update(re.findall(r"::(\w+)\s*\(", part))
    return knob, demo


ENTRY = re.compile(
    r'krate: "(\w+)",\s*name: "([^"]+)",\s*summary:\s*"(?:[^"\\]|\\.)*",\s*covers: &\[([^\]]*)\]',
    re.S)
rows, totals = [], {"knob": 0, "demo": 0, "-": 0}
for f in sorted(SC.glob("*.rs")):
    knob, demo = demo_usage(f)
    for krate, entry, covers in ENTRY.findall(f.read_text()):
        if krate in ("kit", "charts"):
            continue
        api = fns_by_type(krate.replace("_", "-"))
        types = re.findall(r'"(\w+)"', covers)
        extra = ([t + "State" for t in types] + [t + "Event" for t in types]
                 + [t.removesuffix("View") + "Event" for t in types])
        for t in dict.fromkeys(types + extra):
            for m in dict.fromkeys(api.get(t, [])):
                st = "knob" if m in knob else "demo" if m in demo else "-"
                totals[st] += 1
                rows.append((krate, entry, t, m, st))

out = ["# Showcase option coverage", "",
       "Generated by `python3 crates/showcase/tools/coverage_audit.py` (name-based heuristic; "
       "hand-written notes are appended from `tools/coverage_tail.md`).",
       "`knob` = live option in a playground, `demo` = shown in a static/stateful example, "
       "`-` = not demonstrated (usually internal plumbing or a getter; see notes).", "",
       f"**Totals:** knob {totals['knob']}, demo {totals['demo']}, missing {totals['-']}", ""]
cur = None
for krate, entry, t, m, st in rows:
    if (krate, entry) != cur:
        cur = (krate, entry)
        out += ["", f"## {krate} / {entry}", "", "| Type | Option / event | Status |",
                "|---|---|---|"]
    out.append(f"| {t} | `{m}` | {st} |")
tail = ROOT / "crates/showcase/tools/coverage_tail.md"
if tail.exists():
    out += ["", tail.read_text().rstrip()]
(ROOT / "crates/showcase/COVERAGE.md").write_text("\n".join(out) + "\n")
print(totals)
if "--missing" in sys.argv:
    for r in rows:
        if r[4] == "-":
            print(*r[:4])
